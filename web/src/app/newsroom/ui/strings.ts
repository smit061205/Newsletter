const TABLES: Record<Lang, Record<StringKey, string>> = { gu, en };

/** A string in `lang`, its {placeholders} filled in. */
export function tr(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  return (TABLES[lang][key] ?? TABLES.gu[key] ?? key).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
